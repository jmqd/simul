//! Five-agent discrete-event simulation of a database connection pool.
//!
//! Agents (`UnknownDestinationPolicy::Panic`, multi-message tick drain):
//! - `load_gen` (proactive): Poisson arrivals with burst window and synchronized
//!   per-request base service draws for high-precision Common Random Numbers.
//! - `app` (reactive): Bounded application worker pool driving multi-stage
//!   request lifecycles (`Fast`, `Slow`, `RpcHold`, `Nested`).
//! - `pool` (reactive): Single or fast/slow bulkhead FIFO connection pool with
//!   cancellable `acquire_timeout` timers and exact nested-pool deadlock detection.
//! - `db` (reactive): Primary database node with Gunther USL contention/coherency
//!   slowdown and optional cancellable `statement_timeout`.
//! - `rpc` (reactive): External downstream HTTP/gRPC dependency.

use std::collections::VecDeque;
use std::collections::hash_map::Entry;

use rustc_hash::{FxBuildHasher, FxHashMap};
use simul::agent::{Agent, AgentContext, AgentId, AgentInitializer, TimerId};
use simul::experiment::{Probability, TrialContext, TrialRng};
use simul::message::Message;
use simul::{DiscreteTime, Halt, Simulation, SimulationError, UnknownDestinationPolicy};

use crate::config::{BulkheadMode, PoolingMode, SimSpec};

/// Maximum queued incoming requests held by `AppServer` before fast 503 load shedding.
const APP_BACKLOG_CAP: usize = 1024;
/// Post-measurement drain tail so late arrivals finish before `Halt::AtTime`.
const DRAIN_MARGIN_MS: DiscreteTime = 500;
/// Zero-contention message-hop round-trip (`app -> pool -> app`) subtracted from pool wait.
const POOL_HOP_OVERHEAD_MS: DiscreteTime = 2;

/// Traffic class of an incoming application request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum RequestClass {
    /// Short OLTP query (1 DB query).
    Fast,
    /// Heavy analytical/reporting query (1 slow DB query).
    Slow,
    /// Two fast DB queries bracketing an external RPC call.
    RpcHold,
    /// Outer query holding connection #1 while acquiring a nested connection #2.
    Nested,
}

/// Logical pool lane for bulkhead isolation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum PoolLane {
    /// Primary (or shared) OLTP connection lane.
    Fast,
    /// Dedicated slow-query quarantine lane (used in [`BulkheadMode::Split`]).
    Slow,
}

/// Opaque handle to one checked-out database connection.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct ConnHandle {
    /// Lane that owns this connection.
    lane: PoolLane,
    /// Monotonic lease sequence number for trace readability.
    lease_id: u64,
}

/// Typed messages exchanged among the five simulation agents.
#[derive(Clone, Copy, Debug)]
pub(crate) enum PoolMsg {
    /// New request generated by `load_gen` and sent to `app`.
    IncomingRequest {
        /// Monotonic request identifier.
        req_id: u64,
        /// Workload class.
        class: RequestClass,
        /// Arrival tick (ms), compact for trace readability; full timestamp is in `Message::queued_time`.
        arrived_at: u32,
        /// Intrinsic base duration for query 1 before USL contention (ms).
        q1_base_ms: f32,
        /// Intrinsic base duration for query 2 before USL contention (ms).
        q2_base_ms: f32,
        /// External RPC duration (ms), used for [`RequestClass::RpcHold`].
        rpc_ms: u16,
    },
    /// `app` requests a connection from `pool`.
    AcquireConn {
        /// Request identifier.
        req_id: u64,
        /// Target bulkhead lane.
        lane: PoolLane,
        /// Whether the requester already holds an outer connection on the same lane.
        is_nested: bool,
    },
    /// `pool` grants a connection handle to `app`.
    ConnGranted {
        /// Request identifier.
        req_id: u64,
        /// Granted connection handle.
        conn: ConnHandle,
    },
    /// `pool` rejects a waiting request because `acquire_timeout_ms` expired.
    ConnTimedOut {
        /// Request identifier.
        req_id: u64,
    },
    /// `app` returns a connection handle to `pool`.
    ReleaseConn {
        /// Connection being returned.
        conn: ConnHandle,
    },
    /// Self-scheduled cancellable timeout inside `pool`.
    AcquireTimerFired {
        /// Request identifier.
        req_id: u64,
        /// Lane where the waiter is queued.
        lane: PoolLane,
        /// Mirrors [`PoolMsg::AcquireConn::is_nested`].
        is_nested: bool,
    },
    /// `app` submits a SQL query to `db`.
    RunQuery {
        /// Request identifier.
        req_id: u64,
        /// Intrinsic base execution time before USL slowdown (ms).
        base_ms: f32,
    },
    /// `db` returns query completion or statement-timeout abort to `app`.
    QueryResult {
        /// Request identifier.
        req_id: u64,
        /// `true` if completed normally, `false` if aborted by `statement_timeout`.
        ok: bool,
        /// Observed DB execution duration (ms).
        exec_ms: DiscreteTime,
    },
    /// Self-scheduled normal query completion inside `db`.
    QueryCompleted {
        /// Unique query sequence number.
        query_seq: u64,
    },
    /// Self-scheduled cancellable `statement_timeout` inside `db`.
    StatementTimeoutFired {
        /// Unique query sequence number.
        query_seq: u64,
    },
    /// `app` invokes the external RPC service.
    CallRpc {
        /// Request identifier.
        req_id: u64,
        /// Synchronized RPC latency (ms).
        delay_ms: u16,
    },
    /// `rpc` notifies `app` that the external call completed.
    RpcDone {
        /// Request identifier.
        req_id: u64,
    },
}

/// Draws a Poisson arrival count using Knuth's exact product algorithm with a
/// precomputed `exp(-lambda)` threshold.
fn draw_poisson_threshold(rng: &mut TrialRng, threshold: f64) -> usize {
    let mut count = 0_usize;
    let mut prod = 1.0_f64;
    loop {
        prod *= rng.uniform_f64().max(f64::MIN_POSITIVE);
        if prod <= threshold || count >= 32 {
            return count;
        }
        count += 1;
    }
}

/// Draws a unit-mean lognormal multiplier (`E[X] = 1.0`) via Box-Muller transform.
fn draw_lognormal_unit(rng: &mut TrialRng, sigma: f64) -> f64 {
    let u1 = rng.uniform_f64().max(1e-12);
    let u2 = rng.uniform_f64();
    let z = (-2.0 * u1.ln()).sqrt() * (std::f64::consts::TAU * u2).cos();
    ((-0.5 * sigma).mul_add(sigma, sigma * z)).exp()
}

/// Advances `rng` by two draws (matching one [`draw_lognormal_unit`] call)
/// without evaluating Box-Muller or `exp`.
#[inline]
fn skip_lognormal_unit(rng: &mut TrialRng) {
    let _ = rng.next_u64();
    let _ = rng.next_u64();
}

/// Proactive Poisson workload generator with synchronized per-request complexity draws.
#[derive(Clone, Debug)]
struct LoadGen {
    /// Simulation specification.
    spec: SimSpec,
    /// Precomputed `exp(-lambda)` threshold outside the burst window.
    normal_threshold: Option<f64>,
    /// Precomputed `exp(-lambda)` threshold during the burst window.
    burst_threshold: Option<f64>,
    /// Cumulative class cutoff for `Nested` + `Slow`.
    slow_cutoff: f64,
    /// Cumulative class cutoff for `Nested` + `Slow` + `RpcHold`.
    rpc_cutoff: f64,
    /// Whether to eagerly populate unused payload fields for `Debug` traces.
    eager_payload_fields: bool,
    /// Cached `app` agent ID.
    app_id: Option<AgentId>,
    /// Next monotonic request identifier.
    next_req_id: u64,
}

impl LoadGen {
    /// Creates a workload generator for `spec`.
    fn new(spec: SimSpec, eager_payload_fields: bool) -> Self {
        let w = &spec.workload;
        let normal_lambda = (w.rps * 1.0) / 1000.0;
        let burst_lambda = (w.rps * w.burst_mult) / 1000.0;
        let slow_cutoff = w.nested_frac + w.slow_frac;
        let rpc_cutoff = slow_cutoff + w.rpc_hold_frac;
        Self {
            spec,
            normal_threshold: (normal_lambda > 0.0).then(|| (-normal_lambda).exp()),
            burst_threshold: (burst_lambda > 0.0).then(|| (-burst_lambda).exp()),
            slow_cutoff,
            rpc_cutoff,
            eager_payload_fields,
            app_id: None,
            next_req_id: 1,
        }
    }

    /// Generates one incoming request payload using the per-tick RNG.
    fn sample_request(&mut self, rng: &mut TrialRng, now: DiscreteTime, is_last: bool) -> PoolMsg {
        let w = &self.spec.workload;
        let req_id = self.next_req_id;
        self.next_req_id += 1;
        let u = rng.uniform_f64();
        let class = if u < w.nested_frac {
            RequestClass::Nested
        } else if u < self.slow_cutoff {
            RequestClass::Slow
        } else if u < self.rpc_cutoff {
            RequestClass::RpcHold
        } else {
            RequestClass::Fast
        };
        let eager = self.eager_payload_fields;
        let need_fast_j1 = class != RequestClass::Slow;
        let need_fast_j2 = eager || matches!(class, RequestClass::RpcHold | RequestClass::Nested);
        let need_slow_j = class == RequestClass::Slow;
        let need_rpc_j = eager || class == RequestClass::RpcHold;

        let fast_j1 = if need_fast_j1 {
            draw_lognormal_unit(rng, 0.25)
        } else {
            skip_lognormal_unit(rng);
            0.0
        };
        let fast_j2 = if need_fast_j2 {
            draw_lognormal_unit(rng, 0.25)
        } else if need_slow_j || need_rpc_j || !is_last {
            skip_lognormal_unit(rng);
            0.0
        } else {
            0.0
        };
        let slow_j = if need_slow_j {
            draw_lognormal_unit(rng, 0.55)
        } else if need_rpc_j || !is_last {
            skip_lognormal_unit(rng);
            0.0
        } else {
            0.0
        };
        let rpc_j = if need_rpc_j {
            draw_lognormal_unit(rng, 0.25)
        } else if !is_last {
            skip_lognormal_unit(rng);
            0.0
        } else {
            0.0
        };
        #[allow(clippy::cast_possible_truncation)]
        let q1_base_ms = if class == RequestClass::Slow {
            (w.slow_ms * slow_j).clamp(1.0, 20_000.0) as f32
        } else {
            (w.fast_ms * fast_j1).clamp(1.0, 2_000.0) as f32
        };
        #[allow(clippy::cast_possible_truncation)]
        let q2_base_ms = if need_fast_j2 {
            (w.fast_ms * fast_j2).clamp(1.0, 2_000.0) as f32
        } else {
            0.0
        };
        #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
        let rpc_ms = if need_rpc_j {
            (w.rpc_ms * rpc_j).round().clamp(1.0, 10_000.0) as u16
        } else {
            0
        };
        PoolMsg::IncomingRequest {
            req_id,
            class,
            arrived_at: u32::try_from(now).unwrap_or(u32::MAX),
            q1_base_ms,
            q2_base_ms,
            rpc_ms,
        }
    }
}

impl Agent<PoolMsg> for LoadGen {
    fn on_tick(&mut self, ctx: &mut AgentContext<'_, PoolMsg>) {
        if self.app_id.is_none() {
            self.app_id = ctx.agent_id("app");
        }
        let Some(app_id) = self.app_id else {
            return;
        };
        let now = ctx.time();
        let w = &self.spec.workload;
        let threshold = if now >= w.burst_start_ms && now < w.burst_end_ms {
            self.burst_threshold
        } else {
            self.normal_threshold
        };
        let Some(threshold) = threshold else {
            return;
        };
        let mut rng = ctx.rng();
        let arrivals = draw_poisson_threshold(&mut rng, threshold);
        for idx in 0..arrivals {
            let msg = self.sample_request(&mut rng, now, idx + 1 == arrivals);
            ctx.send_to(app_id, msg);
        }
    }
}

/// Current lifecycle stage of an active request inside `AppServer`.
#[derive(Clone, Copy, Debug)]
enum ReqStage {
    /// Waiting for its first database connection.
    AcquiringFirst,
    /// Executing SQL query #1 on `conn`.
    QueryFirst {
        /// Checked-out connection handle.
        conn: ConnHandle,
    },
    /// Executing external RPC, optionally holding `held_conn` in Session mode.
    InExternalRpc {
        /// Connection held across RPC (`Some` in Session mode, `None` in Transaction mode).
        held_conn: Option<ConnHandle>,
    },
    /// Re-acquiring a connection after external RPC (Transaction mode only).
    AcquiringAfterRpc,
    /// Holding `first_conn` while blocked waiting for a nested 2nd connection.
    AcquiringNested {
        /// Outer connection held during nested acquisition.
        first_conn: ConnHandle,
    },
    /// Executing SQL query #2 (after RPC or nested).
    QuerySecond {
        /// Optional outer fast-lane lease ID held by a nested request (`0` if none).
        first_fast_lease: u64,
        /// Connection running query #2.
        second_conn: ConnHandle,
    },
}

/// Active worker state for one in-flight request in `AppServer`.
#[derive(Clone, Copy, Debug)]
struct ActiveRequest {
    /// Workload class.
    class: RequestClass,
    /// Synchronized external RPC latency (ms).
    rpc_ms: u16,
    /// Arrival timestamp from `load_gen` (ms).
    arrived_at: DiscreteTime,
    /// Timestamp when the current pool acquisition started (ms).
    acquire_sent_at: DiscreteTime,
    /// Accumulated pool queue wait time across acquisitions (ms).
    total_pool_wait_ms: DiscreteTime,
    /// Accumulated DB execution time across queries (ms).
    total_db_exec_ms: DiscreteTime,
    /// Base duration of query #1 (ms).
    q1_base_ms: f32,
    /// Base duration of query #2 (ms).
    q2_base_ms: f32,
    /// Current state-machine stage.
    stage: ReqStage,
}

/// Queued incoming request waiting for a free application worker thread.
#[derive(Clone, Copy, Debug)]
struct QueuedRequest {
    /// Request identifier.
    req_id: u64,
    /// Workload class.
    class: RequestClass,
    /// Synchronized external RPC latency (ms).
    rpc_ms: u16,
    /// Arrival timestamp (ms).
    arrived_at: DiscreteTime,
    /// Base duration of query #1 (ms).
    q1_base_ms: f32,
    /// Base duration of query #2 (ms).
    q2_base_ms: f32,
}

/// Bounded application worker pool and request-lifecycle telemetry collector.
#[derive(Clone, Debug)]
struct AppServer {
    /// Simulation specification.
    spec: SimSpec,
    /// Measurement window end tick (exclusive).
    measure_end_ms: DiscreteTime,
    /// Cached peer agent IDs.
    pool_id: Option<AgentId>,
    /// Cached database agent ID.
    db_id: Option<AgentId>,
    /// Cached external RPC agent ID.
    rpc_id: Option<AgentId>,
    /// Active requests currently running on worker threads.
    active: FxHashMap<u64, ActiveRequest>,
    /// Requests queued waiting for an application worker.
    backlog: VecDeque<QueuedRequest>,
    /// Requests arriving inside `[warmup_ms, measure_end_ms)`.
    measured_arrived: u64,
    /// Measured requests that completed successfully.
    measured_completed: u64,
    /// Measured requests that failed due to pool `acquire_timeout`.
    measured_acquire_timeouts: u64,
    /// Measured requests that failed due to DB `statement_timeout`.
    measured_stmt_timeouts: u64,
    /// End-to-end latencies (ms) of completed measured requests.
    all_latencies: Vec<DiscreteTime>,
    /// End-to-end latencies (ms) of completed fast-OLTP measured requests.
    fast_latencies: Vec<DiscreteTime>,
    /// Pool queue wait times (ms) of completed measured requests.
    pool_waits: Vec<DiscreteTime>,
    /// DB execution times (ms) of completed measured requests.
    db_execs: Vec<DiscreteTime>,
}

impl AppServer {
    /// Creates an application server governed by `spec`.
    fn new(spec: SimSpec) -> Self {
        let measure_end_ms = spec
            .workload
            .horizon_ms
            .saturating_sub(DRAIN_MARGIN_MS)
            .max(spec.workload.warmup_ms + 1);
        let est_measured = if spec.pool.halt_on_deadlock {
            0
        } else {
            let window_ms = measure_end_ms.saturating_sub(spec.workload.warmup_ms) as f64;
            #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
            let raw = (window_ms * spec.workload.rps / 1000.0 * 1.25).clamp(0.0, 16_384.0) as usize;
            raw
        };
        let active_cap = spec.pool.app_workers.saturating_mul(2).max(16);
        Self {
            spec,
            measure_end_ms,
            pool_id: None,
            db_id: None,
            rpc_id: None,
            active: FxHashMap::with_capacity_and_hasher(active_cap, FxBuildHasher),
            backlog: VecDeque::new(),
            measured_arrived: 0,
            measured_completed: 0,
            measured_acquire_timeouts: 0,
            measured_stmt_timeouts: 0,
            all_latencies: Vec::with_capacity(est_measured),
            fast_latencies: Vec::with_capacity(est_measured),
            pool_waits: Vec::with_capacity(est_measured),
            db_execs: Vec::with_capacity(est_measured),
        }
    }

    /// Resolves and caches peer agent IDs once.
    fn resolve_peers(&mut self, ctx: &AgentContext<'_, PoolMsg>) {
        if self.pool_id.is_none() {
            self.pool_id = ctx.agent_id("pool");
            self.db_id = ctx.agent_id("db");
            self.rpc_id = ctx.agent_id("rpc");
        }
    }

    /// Returns whether `arrived_at` falls inside the measured steady-state + burst window.
    const fn is_measured(&self, arrived_at: DiscreteTime) -> bool {
        arrived_at >= self.spec.workload.warmup_ms && arrived_at < self.measure_end_ms
    }

    /// Selects the pool lane for `class` under the active bulkhead configuration.
    const fn lane_for(&self, class: RequestClass) -> PoolLane {
        match (self.spec.pool.bulkhead, class) {
            (BulkheadMode::Split { .. }, RequestClass::Slow) => PoolLane::Slow,
            (BulkheadMode::Shared, _)
            | (
                BulkheadMode::Split { .. },
                RequestClass::Fast | RequestClass::RpcHold | RequestClass::Nested,
            ) => PoolLane::Fast,
        }
    }

    /// Admits `req` onto a free worker thread and initiates connection acquisition.
    fn start_request(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, req: QueuedRequest) {
        let Some(pool_id) = self.pool_id else {
            return;
        };
        let now = ctx.time();
        let lane = self.lane_for(req.class);
        self.active.insert(
            req.req_id,
            ActiveRequest {
                class: req.class,
                rpc_ms: req.rpc_ms,
                arrived_at: req.arrived_at,
                acquire_sent_at: now,
                total_pool_wait_ms: 0,
                total_db_exec_ms: 0,
                q1_base_ms: req.q1_base_ms,
                q2_base_ms: req.q2_base_ms,
                stage: ReqStage::AcquiringFirst,
            },
        );
        ctx.send_to(
            pool_id,
            PoolMsg::AcquireConn {
                req_id: req.req_id,
                lane,
                is_nested: false,
            },
        );
    }

    /// Frees a worker slot and admits the next queued request if any.
    fn admit_from_backlog(&mut self, ctx: &mut AgentContext<'_, PoolMsg>) {
        while self.active.len() < self.spec.pool.app_workers {
            let Some(next) = self.backlog.pop_front() else {
                break;
            };
            self.start_request(ctx, next);
        }
    }

    /// Records a completed request's latency breakdown and frees its worker.
    fn finish_success(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        req: ActiveRequest,
        now: DiscreteTime,
    ) {
        if self.is_measured(req.arrived_at) {
            let e2e = now.saturating_sub(req.arrived_at);
            self.measured_completed += 1;
            self.all_latencies.push(e2e);
            if req.class == RequestClass::Fast {
                self.fast_latencies.push(e2e);
            }
            self.pool_waits.push(req.total_pool_wait_ms);
            self.db_execs.push(req.total_db_exec_ms);
        }
        self.admit_from_backlog(ctx);
    }

    /// Handles a granted database connection for `req_id`.
    fn handle_conn_granted(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        req_id: u64,
        conn: ConnHandle,
    ) {
        let Some(db_id) = self.db_id else {
            return;
        };
        let now = ctx.time();
        let Some(entry) = self.active.get_mut(&req_id) else {
            return;
        };
        let wait = now
            .saturating_sub(entry.acquire_sent_at)
            .saturating_sub(POOL_HOP_OVERHEAD_MS);
        entry.total_pool_wait_ms = entry.total_pool_wait_ms.saturating_add(wait);
        match entry.stage {
            ReqStage::AcquiringFirst => {
                entry.stage = ReqStage::QueryFirst { conn };
                ctx.send_to(
                    db_id,
                    PoolMsg::RunQuery {
                        req_id,
                        base_ms: entry.q1_base_ms,
                    },
                );
            }
            ReqStage::AcquiringAfterRpc => {
                entry.stage = ReqStage::QuerySecond {
                    first_fast_lease: 0,
                    second_conn: conn,
                };
                ctx.send_to(
                    db_id,
                    PoolMsg::RunQuery {
                        req_id,
                        base_ms: entry.q2_base_ms,
                    },
                );
            }
            ReqStage::AcquiringNested { first_conn } => {
                entry.stage = ReqStage::QuerySecond {
                    first_fast_lease: first_conn.lease_id,
                    second_conn: conn,
                };
                ctx.send_to(
                    db_id,
                    PoolMsg::RunQuery {
                        req_id,
                        base_ms: entry.q2_base_ms,
                    },
                );
            }
            ReqStage::QueryFirst { .. }
            | ReqStage::InExternalRpc { .. }
            | ReqStage::QuerySecond { .. } => {}
        }
    }

    /// Handles a pool acquisition timeout, always releasing any outer held connection.
    fn handle_conn_timeout(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, req_id: u64) {
        let Some(req) = self.active.remove(&req_id) else {
            return;
        };
        if let ReqStage::AcquiringNested { first_conn } = req.stage {
            if let Some(pool_id) = self.pool_id {
                ctx.send_to(pool_id, PoolMsg::ReleaseConn { conn: first_conn });
            }
        }
        if self.is_measured(req.arrived_at) {
            self.measured_acquire_timeouts += 1;
        }
        self.admit_from_backlog(ctx);
    }

    /// Handles a DB query result (normal completion or statement-timeout abort).
    fn handle_query_result(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        req_id: u64,
        ok: bool,
        exec_ms: DiscreteTime,
    ) {
        let Some(pool_id) = self.pool_id else {
            return;
        };
        let now = ctx.time();
        let Entry::Occupied(mut occupied) = self.active.entry(req_id) else {
            return;
        };
        let req_mut = occupied.get_mut();
        req_mut.total_db_exec_ms = req_mut.total_db_exec_ms.saturating_add(exec_ms);
        match req_mut.stage {
            ReqStage::QueryFirst { conn } => {
                if !ok {
                    let req = occupied.remove();
                    ctx.send_to(pool_id, PoolMsg::ReleaseConn { conn });
                    if self.is_measured(req.arrived_at) {
                        self.measured_stmt_timeouts += 1;
                    }
                    self.admit_from_backlog(ctx);
                    return;
                }
                match req_mut.class {
                    RequestClass::Fast | RequestClass::Slow => {
                        let req = occupied.remove();
                        ctx.send_to(pool_id, PoolMsg::ReleaseConn { conn });
                        self.finish_success(ctx, req, now);
                    }
                    RequestClass::RpcHold => {
                        let held_conn = match self.spec.pool.pooling {
                            PoolingMode::Session => Some(conn),
                            PoolingMode::Transaction => {
                                ctx.send_to(pool_id, PoolMsg::ReleaseConn { conn });
                                None
                            }
                        };
                        req_mut.stage = ReqStage::InExternalRpc { held_conn };
                        let delay_ms = req_mut.rpc_ms;
                        if let Some(rpc_id) = self.rpc_id {
                            ctx.send_to(rpc_id, PoolMsg::CallRpc { req_id, delay_ms });
                        }
                    }
                    RequestClass::Nested => {
                        req_mut.acquire_sent_at = now;
                        req_mut.stage = ReqStage::AcquiringNested { first_conn: conn };
                        ctx.send_to(
                            pool_id,
                            PoolMsg::AcquireConn {
                                req_id,
                                lane: PoolLane::Fast,
                                is_nested: true,
                            },
                        );
                    }
                }
            }
            ReqStage::QuerySecond {
                first_fast_lease,
                second_conn,
            } => {
                let req = occupied.remove();
                ctx.send_to(pool_id, PoolMsg::ReleaseConn { conn: second_conn });
                if first_fast_lease != 0 {
                    ctx.send_to(
                        pool_id,
                        PoolMsg::ReleaseConn {
                            conn: ConnHandle {
                                lane: PoolLane::Fast,
                                lease_id: first_fast_lease,
                            },
                        },
                    );
                }
                if ok {
                    self.finish_success(ctx, req, now);
                } else {
                    if self.is_measured(req.arrived_at) {
                        self.measured_stmt_timeouts += 1;
                    }
                    self.admit_from_backlog(ctx);
                }
            }
            ReqStage::AcquiringFirst
            | ReqStage::InExternalRpc { .. }
            | ReqStage::AcquiringAfterRpc
            | ReqStage::AcquiringNested { .. } => {
                occupied.remove();
            }
        }
    }

    /// Handles external RPC completion, either reusing the held connection or re-acquiring.
    fn handle_rpc_done(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, req_id: u64) {
        let now = ctx.time();
        let Some(entry) = self.active.get_mut(&req_id) else {
            return;
        };
        let ReqStage::InExternalRpc { held_conn } = entry.stage else {
            return;
        };
        if let Some(conn) = held_conn {
            entry.stage = ReqStage::QuerySecond {
                first_fast_lease: 0,
                second_conn: conn,
            };
            if let Some(db_id) = self.db_id {
                ctx.send_to(
                    db_id,
                    PoolMsg::RunQuery {
                        req_id,
                        base_ms: entry.q2_base_ms,
                    },
                );
            }
        } else {
            entry.acquire_sent_at = now;
            entry.stage = ReqStage::AcquiringAfterRpc;
            if let Some(pool_id) = self.pool_id {
                ctx.send_to(
                    pool_id,
                    PoolMsg::AcquireConn {
                        req_id,
                        lane: PoolLane::Fast,
                        is_nested: false,
                    },
                );
            }
        }
    }
}

impl Agent<PoolMsg> for AppServer {
    fn on_message(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, msg: &Message<PoolMsg>) {
        self.resolve_peers(ctx);
        match msg.payload {
            PoolMsg::IncomingRequest {
                req_id,
                class,
                arrived_at,
                q1_base_ms,
                q2_base_ms,
                rpc_ms,
            } => {
                let arrived_at = if arrived_at == u32::MAX {
                    msg.queued_time
                } else {
                    DiscreteTime::from(arrived_at)
                };
                if self.is_measured(arrived_at) {
                    self.measured_arrived += 1;
                }
                let item = QueuedRequest {
                    req_id,
                    class,
                    rpc_ms,
                    arrived_at,
                    q1_base_ms,
                    q2_base_ms,
                };
                if self.active.len() < self.spec.pool.app_workers {
                    self.start_request(ctx, item);
                } else if self.backlog.len() < APP_BACKLOG_CAP {
                    self.backlog.push_back(item);
                }
            }
            PoolMsg::ConnGranted { req_id, conn } => {
                self.handle_conn_granted(ctx, req_id, conn);
            }
            PoolMsg::ConnTimedOut { req_id } => {
                self.handle_conn_timeout(ctx, req_id);
            }
            PoolMsg::QueryResult {
                req_id,
                ok,
                exec_ms,
            } => {
                self.handle_query_result(ctx, req_id, ok, exec_ms);
            }
            PoolMsg::RpcDone { req_id } => {
                self.handle_rpc_done(ctx, req_id);
            }
            PoolMsg::AcquireConn { .. }
            | PoolMsg::ReleaseConn { .. }
            | PoolMsg::AcquireTimerFired { .. }
            | PoolMsg::RunQuery { .. }
            | PoolMsg::QueryCompleted { .. }
            | PoolMsg::StatementTimeoutFired { .. }
            | PoolMsg::CallRpc { .. } => {}
        }
    }
}

/// One queued connection requester waiting inside a [`PoolLaneState`].
#[derive(Clone, Copy, Debug)]
struct PoolWaiter {
    /// Waiting request identifier.
    req_id: u64,
    /// Whether this waiter already holds an outer connection on this lane.
    is_nested: bool,
    /// Cancellable acquire-timeout timer handle.
    timer: TimerId,
}

/// State of a single FIFO connection-pool lane.
#[derive(Clone, Debug)]
struct PoolLaneState {
    /// Maximum concurrent connections in this lane.
    capacity: usize,
    /// Connections currently checked out.
    in_use: usize,
    /// FIFO queue of waiting acquirers.
    wait_queue: VecDeque<PoolWaiter>,
    /// Number of queued waiters that already hold an outer connection in this lane.
    nested_waiters: usize,
    /// Peak wait-queue depth observed in this lane.
    max_queue_depth: usize,
    /// Whether this lane is currently in a nested-pool deadlock state.
    deadlock_active: bool,
    /// Count of distinct nested-pool deadlock episodes entered.
    deadlock_events: u64,
    /// First tick at which exact nested-pool deadlock occurred, if any.
    first_deadlock_tick: Option<DiscreteTime>,
}

impl PoolLaneState {
    /// Creates an empty pool lane with `capacity` connections.
    const fn new(capacity: usize) -> Self {
        Self {
            capacity,
            in_use: 0,
            wait_queue: VecDeque::new(),
            nested_waiters: 0,
            max_queue_depth: 0,
            deadlock_active: false,
            deadlock_events: 0,
            first_deadlock_tick: None,
        }
    }
}

/// Connection pool supporting shared or fast/slow bulkhead lanes, cancellable
/// acquire timeouts, and exact nested-pool deadlock detection.
#[derive(Clone, Debug)]
struct ConnPool {
    /// Primary (or shared) lane.
    fast_lane: PoolLaneState,
    /// Optional slow-query quarantine lane.
    slow_lane: PoolLaneState,
    /// Maximum wait duration before timing out (ms).
    acquire_timeout_ms: DiscreteTime,
    /// Whether to emit a halt interrupt immediately on exact nested-pool deadlock.
    halt_on_deadlock: bool,
    /// Cached `app` agent ID.
    app_id: Option<AgentId>,
    /// Monotonic connection lease ID.
    next_lease_id: u64,
}

impl ConnPool {
    /// Builds a connection pool from `spec`.
    fn new(spec: SimSpec) -> Self {
        let total = spec.pool.pool_size.max(1);
        let (fast_cap, slow_cap) = match spec.pool.bulkhead {
            BulkheadMode::Shared => (total, 0),
            BulkheadMode::Split { slow_cap } => {
                if total <= 1 {
                    (1, 0)
                } else {
                    let s = slow_cap.clamp(1, total - 1);
                    (total - s, s)
                }
            }
        };
        Self {
            fast_lane: PoolLaneState::new(fast_cap),
            slow_lane: PoolLaneState::new(slow_cap),
            acquire_timeout_ms: spec.pool.acquire_timeout_ms,
            halt_on_deadlock: spec.pool.halt_on_deadlock,
            app_id: None,
            next_lease_id: 1,
        }
    }

    /// Resolves `lane` to the effective mutable [`PoolLaneState`].
    fn lane_mut(&mut self, lane: PoolLane) -> (PoolLane, &mut PoolLaneState) {
        if lane == PoolLane::Slow && self.slow_lane.capacity > 0 {
            (PoolLane::Slow, &mut self.slow_lane)
        } else {
            (PoolLane::Fast, &mut self.fast_lane)
        }
    }

    /// Handles a connection acquisition request, queueing with a cancellable timer if full.
    fn handle_acquire(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        app_id: AgentId,
        req_id: u64,
        lane: PoolLane,
        is_nested: bool,
    ) {
        let acquire_timeout_ms = self.acquire_timeout_ms;
        let halt_on_deadlock = self.halt_on_deadlock;
        let lease_id = self.next_lease_id;
        let (effective_lane, state) = self.lane_mut(lane);
        if state.in_use < state.capacity {
            state.in_use += 1;
            self.next_lease_id = lease_id + 1;
            ctx.send_to(
                app_id,
                PoolMsg::ConnGranted {
                    req_id,
                    conn: ConnHandle {
                        lane: effective_lane,
                        lease_id,
                    },
                },
            );
            return;
        }
        let timer = ctx.send_after(
            acquire_timeout_ms,
            ctx.id(),
            PoolMsg::AcquireTimerFired {
                req_id,
                lane: effective_lane,
                is_nested,
            },
        );
        state.wait_queue.push_back(PoolWaiter {
            req_id,
            is_nested,
            timer,
        });
        state.max_queue_depth = state.max_queue_depth.max(state.wait_queue.len());
        if is_nested {
            state.nested_waiters += 1;
        }
        if state.in_use == state.capacity && state.nested_waiters >= state.capacity {
            if !state.deadlock_active {
                state.deadlock_active = true;
                state.deadlock_events += 1;
                if state.first_deadlock_tick.is_none() {
                    state.first_deadlock_tick = Some(ctx.time());
                }
            }
            if halt_on_deadlock {
                ctx.send_halt_interrupt("nested_pool_deadlock");
            }
        }
    }

    /// Handles a released connection, cancelling the next waiter's timeout timer if queued.
    fn handle_release(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        app_id: AgentId,
        conn: ConnHandle,
    ) {
        let (_, state) = self.lane_mut(conn.lane);
        if let Some(waiter) = state.wait_queue.pop_front() {
            ctx.cancel_timer(waiter.timer);
            if waiter.is_nested {
                state.nested_waiters = state.nested_waiters.saturating_sub(1);
            }
            if state.nested_waiters < state.capacity {
                state.deadlock_active = false;
            }
            ctx.send_to(
                app_id,
                PoolMsg::ConnGranted {
                    req_id: waiter.req_id,
                    conn,
                },
            );
        } else {
            state.in_use = state.in_use.saturating_sub(1);
            state.deadlock_active = false;
        }
    }

    /// Handles an expired `acquire_timeout` timer for a still-queued waiter.
    fn handle_acquire_timeout(
        &mut self,
        ctx: &mut AgentContext<'_, PoolMsg>,
        app_id: AgentId,
        req_id: u64,
        lane: PoolLane,
        is_nested: bool,
    ) {
        let (_, state) = self.lane_mut(lane);
        let pos = state
            .wait_queue
            .iter()
            .position(|w| w.req_id == req_id && w.is_nested == is_nested);
        if let Some(idx) = pos {
            if let Some(removed) = state.wait_queue.remove(idx) {
                if removed.is_nested {
                    state.nested_waiters = state.nested_waiters.saturating_sub(1);
                }
                if state.nested_waiters < state.capacity {
                    state.deadlock_active = false;
                }
                ctx.send_to(app_id, PoolMsg::ConnTimedOut { req_id });
            }
        }
    }
}

impl Agent<PoolMsg> for ConnPool {
    fn on_message(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, msg: &Message<PoolMsg>) {
        if self.app_id.is_none() {
            self.app_id = ctx.agent_id("app");
        }
        let Some(app_id) = self.app_id else {
            return;
        };
        match msg.payload {
            PoolMsg::AcquireConn {
                req_id,
                lane,
                is_nested,
            } => self.handle_acquire(ctx, app_id, req_id, lane, is_nested),
            PoolMsg::ReleaseConn { conn } => self.handle_release(ctx, app_id, conn),
            PoolMsg::AcquireTimerFired {
                req_id,
                lane,
                is_nested,
            } => self.handle_acquire_timeout(ctx, app_id, req_id, lane, is_nested),
            PoolMsg::IncomingRequest { .. }
            | PoolMsg::ConnGranted { .. }
            | PoolMsg::ConnTimedOut { .. }
            | PoolMsg::RunQuery { .. }
            | PoolMsg::QueryResult { .. }
            | PoolMsg::QueryCompleted { .. }
            | PoolMsg::StatementTimeoutFired { .. }
            | PoolMsg::CallRpc { .. }
            | PoolMsg::RpcDone { .. } => {}
        }
    }
}

/// One executing SQL query inside `Database`.
#[derive(Clone, Copy, Debug)]
struct ActiveQuery {
    /// Request identifier.
    req_id: u64,
    /// Start tick (ms).
    started_at: DiscreteTime,
    /// Cancellable completion timer.
    done_timer: TimerId,
    /// Optional cancellable `statement_timeout` timer.
    timeout_timer: Option<TimerId>,
}

/// Primary database node applying Gunther's USL contention/coherency slowdown
/// and optional cancellable `statement_timeout`.
#[derive(Clone, Debug)]
struct Database {
    /// Simulation specification.
    spec: SimSpec,
    /// Precomputed USL slowdown factors indexed by concurrent query count.
    usl_table: Vec<f64>,
    /// Cached `app` agent ID.
    app_id: Option<AgentId>,
    /// Next unique query sequence ID.
    next_query_seq: u64,
    /// Currently executing queries.
    active: FxHashMap<u64, ActiveQuery>,
    /// Peak concurrent queries observed after warmup.
    max_active_post_warmup: usize,
    /// Time-weighted integral of active concurrency after warmup.
    active_area_post_warmup: f64,
    /// Last tick at which `active_area_post_warmup` was updated.
    last_area_tick: DiscreteTime,
}

impl Database {
    /// Creates a database server governed by `spec`.
    fn new(spec: SimSpec) -> Self {
        let max_conc = spec.pool.pool_size.max(1);
        let usl_table = (0..=max_conc)
            .map(|c| spec.hardware.usl_slowdown(c))
            .collect();
        let active_cap = max_conc.saturating_mul(2).max(16);
        Self {
            spec,
            usl_table,
            app_id: None,
            next_query_seq: 1,
            active: FxHashMap::with_capacity_and_hasher(active_cap, FxBuildHasher),
            max_active_post_warmup: 0,
            active_area_post_warmup: 0.0,
            last_area_tick: spec.workload.warmup_ms,
        }
    }

    /// Integrates time-weighted active query count up to `now`.
    fn accumulate_area(&mut self, now: DiscreteTime) {
        if now > self.last_area_tick {
            let dt = now.saturating_sub(self.last_area_tick) as f64;
            self.active_area_post_warmup =
                (self.active.len() as f64).mul_add(dt, self.active_area_post_warmup);
            self.last_area_tick = now;
        }
    }

    /// Returns exact time-weighted mean active DB concurrency from `warmup_ms` to `end_tick`.
    fn mean_active_until(&self, end_tick: DiscreteTime) -> f64 {
        let warmup = self.spec.workload.warmup_ms;
        if end_tick <= warmup {
            return 0.0;
        }
        let mut area = self.active_area_post_warmup;
        if end_tick > self.last_area_tick {
            let dt = end_tick.saturating_sub(self.last_area_tick) as f64;
            area = (self.active.len() as f64).mul_add(dt, area);
        }
        area / end_tick.saturating_sub(warmup) as f64
    }
}

impl Agent<PoolMsg> for Database {
    fn on_message(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, msg: &Message<PoolMsg>) {
        if self.app_id.is_none() {
            self.app_id = ctx.agent_id("app");
        }
        let Some(app_id) = self.app_id else {
            return;
        };
        let now = ctx.time();
        match msg.payload {
            PoolMsg::RunQuery { req_id, base_ms } => {
                self.accumulate_area(now);
                let concurrency = self.active.len() + 1;
                if now >= self.spec.workload.warmup_ms {
                    self.max_active_post_warmup = self.max_active_post_warmup.max(concurrency);
                }
                let slowdown = self
                    .usl_table
                    .get(concurrency)
                    .copied()
                    .unwrap_or_else(|| self.spec.hardware.usl_slowdown(concurrency));
                #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
                let exec_ms =
                    (f64::from(base_ms) * slowdown).round().clamp(1.0, 60_000.0) as DiscreteTime;
                let query_seq = self.next_query_seq;
                self.next_query_seq += 1;
                let done_timer =
                    ctx.send_after(exec_ms, ctx.id(), PoolMsg::QueryCompleted { query_seq });
                let timeout_timer = self.spec.hardware.statement_timeout_ms.map(|limit| {
                    ctx.send_after(
                        limit,
                        ctx.id(),
                        PoolMsg::StatementTimeoutFired { query_seq },
                    )
                });
                self.active.insert(
                    query_seq,
                    ActiveQuery {
                        req_id,
                        started_at: now,
                        done_timer,
                        timeout_timer,
                    },
                );
            }
            PoolMsg::QueryCompleted { query_seq } => {
                self.accumulate_area(now);
                if let Some(q) = self.active.remove(&query_seq) {
                    if let Some(t) = q.timeout_timer {
                        ctx.cancel_timer(t);
                    }
                    ctx.send_to(
                        app_id,
                        PoolMsg::QueryResult {
                            req_id: q.req_id,
                            ok: true,
                            exec_ms: now.saturating_sub(q.started_at),
                        },
                    );
                }
            }
            PoolMsg::StatementTimeoutFired { query_seq } => {
                self.accumulate_area(now);
                if let Some(q) = self.active.remove(&query_seq) {
                    ctx.cancel_timer(q.done_timer);
                    ctx.send_to(
                        app_id,
                        PoolMsg::QueryResult {
                            req_id: q.req_id,
                            ok: false,
                            exec_ms: now.saturating_sub(q.started_at),
                        },
                    );
                }
            }
            PoolMsg::IncomingRequest { .. }
            | PoolMsg::AcquireConn { .. }
            | PoolMsg::ConnGranted { .. }
            | PoolMsg::ConnTimedOut { .. }
            | PoolMsg::ReleaseConn { .. }
            | PoolMsg::AcquireTimerFired { .. }
            | PoolMsg::QueryResult { .. }
            | PoolMsg::CallRpc { .. }
            | PoolMsg::RpcDone { .. } => {}
        }
    }
}

/// External HTTP/gRPC dependency delaying replies by the request's RPC latency.
#[derive(Clone, Debug, Default)]
struct ExternalRpc {
    /// Cached `app` agent ID.
    app_id: Option<AgentId>,
}

impl Agent<PoolMsg> for ExternalRpc {
    fn on_message(&mut self, ctx: &mut AgentContext<'_, PoolMsg>, msg: &Message<PoolMsg>) {
        if self.app_id.is_none() {
            self.app_id = ctx.agent_id("app");
        }
        let Some(app_id) = self.app_id else {
            return;
        };
        if let PoolMsg::CallRpc { req_id, delay_ms } = msg.payload {
            ctx.send_after(
                DiscreteTime::from(delay_ms.max(1)),
                app_id,
                PoolMsg::RpcDone { req_id },
            );
        }
    }
}

/// Quantitative metrics extracted from one replication of the simulation.
#[derive(Clone, Copy, Debug)]
pub(crate) struct PoolOutcome {
    /// Effective goodput of completed requests during the measurement window (req/s).
    pub(crate) throughput_rps: f64,
    /// Fraction of measured requests that completed successfully in `[0, 1]`.
    pub(crate) success_rate: f64,
    /// Fraction of measured requests rejected by pool `acquire_timeout` in `[0, 1]`.
    pub(crate) timeout_rate: f64,
    /// Fraction of measured requests aborted by DB `statement_timeout` in `[0, 1]`.
    pub(crate) stmt_timeout_rate: f64,
    /// Whether an exact nested-pool deadlock occurred during the run.
    pub(crate) deadlocked: bool,
    /// First tick at which exact deadlock occurred, if any.
    pub(crate) deadlock_tick: Option<DiscreteTime>,
    /// Time-weighted mean concurrent active DB queries after warmup.
    pub(crate) mean_db_active: f64,
    /// Median end-to-end latency of completed requests (ms).
    pub(crate) p50_ms: f64,
    /// 99th percentile end-to-end latency of completed requests (ms).
    pub(crate) p99_ms: f64,
    /// Upper 95% Conditional Value at Risk (expected tail latency above P95, ms).
    pub(crate) cvar95_ms: f64,
    /// 99th percentile latency of fast OLTP requests specifically (ms).
    pub(crate) fast_p99_ms: f64,
    /// 95th percentile pool queue wait duration (ms).
    pub(crate) pool_wait_p95_ms: f64,
    /// 95th percentile DB query execution duration (ms).
    pub(crate) db_exec_p95_ms: f64,
}

/// Builds a deterministic five-agent connection-pool simulation for `spec` and `ctx`.
pub(crate) fn build_simulation(
    spec: &SimSpec,
    ctx: &TrialContext,
) -> Result<Simulation<PoolMsg>, SimulationError> {
    build_simulation_with_options(spec, ctx, true)
}

/// Builds a simulation, optionally skipping unused `IncomingRequest` payload math
/// when payload-level tracing is inactive.
fn build_simulation_with_options(
    spec: &SimSpec,
    ctx: &TrialContext,
    eager_payload_fields: bool,
) -> Result<Simulation<PoolMsg>, SimulationError> {
    Simulation::builder(Halt::AtTime(spec.workload.horizon_ms))
        .trial(ctx)
        .unknown_destination_policy(UnknownDestinationPolicy::Panic)
        .agents([
            AgentInitializer::proactive("load_gen", LoadGen::new(*spec, eager_payload_fields)),
            AgentInitializer::reactive("app", AppServer::new(*spec)).drain_all_messages(),
            AgentInitializer::reactive("pool", ConnPool::new(*spec)).drain_all_messages(),
            AgentInitializer::reactive("db", Database::new(*spec)).drain_all_messages(),
            AgentInitializer::reactive("rpc", ExternalRpc::default()).drain_all_messages(),
        ])
        .build()
}

/// Runs one replication and summarizes throughput, reliability, latency, and deadlock state.
pub(crate) fn evaluate_run(
    spec: &SimSpec,
    ctx: &TrialContext,
) -> Result<PoolOutcome, SimulationError> {
    let mut sim = build_simulation_with_options(spec, ctx, false)?;
    sim.run();
    let end_time = sim.time();
    let penalty_ms = (spec.pool.acquire_timeout_ms * 4).max(500) as f64;
    let Some(pool) = sim
        .find_by_name("pool")
        .and_then(|a| a.downcast_ref::<ConnPool>())
    else {
        return Ok(empty_outcome(penalty_ms));
    };
    let deadlock_events = pool.fast_lane.deadlock_events + pool.slow_lane.deadlock_events;
    let deadlock_tick = pool
        .fast_lane
        .first_deadlock_tick
        .or(pool.slow_lane.first_deadlock_tick);
    let Some(db) = sim
        .find_by_name("db")
        .and_then(|a| a.downcast_ref::<Database>())
    else {
        return Ok(empty_outcome(penalty_ms));
    };
    let mean_db_active = db.mean_active_until(end_time);
    let Some(app) = sim
        .find_by_name_mut("app")
        .and_then(|a| a.downcast_mut::<AppServer>())
    else {
        return Ok(empty_outcome(penalty_ms));
    };
    Ok(summarize_agents(
        spec,
        app,
        deadlock_events,
        deadlock_tick,
        mean_db_active,
        end_time,
        penalty_ms,
    ))
}

/// Computes the exact Type-7 quantile at `p` from a sorted non-empty slice.
fn quantile_sorted(sorted: &[DiscreteTime], p: f64) -> f64 {
    let last = sorted.len() - 1;
    if last == 0 || p <= 0.0 {
        return sorted[0] as f64;
    }
    if p >= 1.0 {
        return sorted[last] as f64;
    }
    let position = p * last as f64;
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let lower_index = (position.floor() as usize).min(last);
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let upper_index = (position.ceil() as usize).min(last);
    let a = sorted[lower_index] as f64;
    if lower_index == upper_index {
        return a;
    }
    let b = sorted[upper_index] as f64;
    let fraction = (position - lower_index as f64).clamp(0.0, 1.0);
    fraction.mul_add(b - a, a)
}

/// Computes the exact Type-7 quantile at `p` in place via linear-time selection.
fn quantile_in_place(values: &mut [DiscreteTime], p: f64, penalty_ms: f64) -> f64 {
    if values.is_empty() {
        return penalty_ms;
    }
    let last = values.len() - 1;
    if last == 0 || p <= 0.0 {
        return values.iter().copied().min().unwrap_or(0) as f64;
    }
    if p >= 1.0 {
        return values.iter().copied().max().unwrap_or(0) as f64;
    }
    let position = p * last as f64;
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let lower_index = (position.floor() as usize).min(last);
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let upper_index = (position.ceil() as usize).min(last);
    let (_, pivot, right) = values.select_nth_unstable(lower_index);
    let a = *pivot as f64;
    if lower_index == upper_index {
        return a;
    }
    let b = right.iter().copied().min().unwrap_or(*pivot) as f64;
    let fraction = (position - lower_index as f64).clamp(0.0, 1.0);
    fraction.mul_add(b - a, a)
}

/// Computes the exact incremental weighted mean matching `QuantileSummary::upper_cvar`.
fn weighted_tail_mean(values: impl Iterator<Item = f64>, partial: Option<(f64, f64)>) -> f64 {
    let mut mean = 0.0_f64;
    let mut weight_sum = 0.0_f64;
    for value in values {
        if weight_sum <= 0.0 {
            mean = value;
            weight_sum = 1.0;
        } else {
            weight_sum += 1.0;
            let step = 1.0 / weight_sum;
            mean = step.mul_add(value - mean, mean);
        }
    }
    if let Some((value, weight)) = partial {
        if weight > 0.0 {
            if weight_sum <= 0.0 {
                mean = value;
            } else {
                weight_sum += weight;
                let step = weight / weight_sum;
                mean = step.mul_add(value - mean, mean);
            }
        }
    }
    mean
}

/// Computes exact `(p50, p99, upper_cvar95)` in place without sorting the lower 95%.
fn all_latency_stats_in_place(values: &mut [DiscreteTime], penalty_ms: f64) -> (f64, f64, f64) {
    let n = values.len();
    if n == 0 {
        return (penalty_ms, penalty_ms, penalty_ms);
    }
    let tail_fraction = 1.0 - Probability::P95.get();
    let mass = tail_fraction * n as f64;
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let full = (mass.floor() as usize).min(n);
    let remainder = (mass - full as f64).clamp(0.0, 1.0);

    if n < 64 || full == 0 || full >= n {
        values.sort_unstable();
        let p50 = quantile_sorted(values, Probability::P50.get());
        let p99 = quantile_sorted(values, Probability::P99.get());
        let cvar95 = if full == 0 {
            values[n - 1] as f64
        } else {
            let partial = if remainder > 0.0 && full < n {
                Some((values[n - full - 1] as f64, remainder))
            } else {
                None
            };
            weighted_tail_mean(values[n - full..].iter().rev().map(|&v| v as f64), partial)
        };
        return (p50, p99, cvar95);
    }

    let tail_start = n - full;
    let (lower_part, partial_val, tail) = values.select_nth_unstable(tail_start - 1);
    tail.sort_unstable();
    let partial = if remainder > 0.0 {
        Some((*partial_val as f64, remainder))
    } else {
        None
    };
    let cvar95 = weighted_tail_mean(tail.iter().rev().map(|&v| v as f64), partial);

    let last = n - 1;
    let p99_pos = Probability::P99.get() * last as f64;
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let p99_lo = (p99_pos.floor() as usize).min(last);
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let p99_hi = (p99_pos.ceil() as usize).min(last);
    let a99 = tail[p99_lo - tail_start] as f64;
    let p99 = if p99_lo == p99_hi {
        a99
    } else {
        let b99 = tail[p99_hi - tail_start] as f64;
        let frac = (p99_pos - p99_lo as f64).clamp(0.0, 1.0);
        frac.mul_add(b99 - a99, a99)
    };

    let p50_pos = Probability::P50.get() * last as f64;
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let p50_lo = (p50_pos.floor() as usize).min(last);
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let p50_hi = (p50_pos.ceil() as usize).min(last);
    let (_, p50_pivot, p50_right) = lower_part.select_nth_unstable(p50_lo);
    let a50 = *p50_pivot as f64;
    let p50 = if p50_lo == p50_hi {
        a50
    } else {
        let b50 = p50_right.iter().copied().min().unwrap_or(*p50_pivot) as f64;
        let frac = (p50_pos - p50_lo as f64).clamp(0.0, 1.0);
        frac.mul_add(b50 - a50, a50)
    };
    (p50, p99, cvar95)
}

/// Extracts [`PoolOutcome`] metrics from finished agents.
fn summarize_agents(
    spec: &SimSpec,
    app: &mut AppServer,
    deadlock_events: u64,
    deadlock_tick: Option<DiscreteTime>,
    mean_db_active: f64,
    end_time: DiscreteTime,
    penalty_ms: f64,
) -> PoolOutcome {
    let window_end = app.measure_end_ms.min(end_time);
    let window_secs = window_end.saturating_sub(spec.workload.warmup_ms).max(1) as f64 / 1000.0;
    let arrived = app.measured_arrived.max(1) as f64;
    let (p50_ms, p99_ms, cvar95_ms) =
        all_latency_stats_in_place(&mut app.all_latencies, penalty_ms);
    let fast_p99_ms =
        quantile_in_place(&mut app.fast_latencies, Probability::P99.get(), penalty_ms);
    let pool_wait_p95_ms =
        quantile_in_place(&mut app.pool_waits, Probability::P95.get(), penalty_ms);
    let db_exec_p95_ms = quantile_in_place(&mut app.db_execs, Probability::P95.get(), penalty_ms);

    PoolOutcome {
        throughput_rps: app.measured_completed as f64 / window_secs,
        success_rate: app.measured_completed as f64 / arrived,
        timeout_rate: app.measured_acquire_timeouts as f64 / arrived,
        stmt_timeout_rate: app.measured_stmt_timeouts as f64 / arrived,
        deadlocked: deadlock_events > 0,
        deadlock_tick,
        mean_db_active,
        p50_ms,
        p99_ms,
        cvar95_ms,
        fast_p99_ms,
        pool_wait_p95_ms,
        db_exec_p95_ms,
    }
}

/// Fallback outcome when an expected agent is missing.
const fn empty_outcome(penalty_ms: f64) -> PoolOutcome {
    PoolOutcome {
        throughput_rps: 0.0,
        success_rate: 0.0,
        timeout_rate: 1.0,
        stmt_timeout_rate: 0.0,
        deadlocked: false,
        deadlock_tick: None,
        mean_db_active: 0.0,
        p50_ms: penalty_ms,
        p99_ms: penalty_ms,
        cvar95_ms: penalty_ms,
        fast_p99_ms: penalty_ms,
        pool_wait_p95_ms: penalty_ms,
        db_exec_p95_ms: penalty_ms,
    }
}

#[cfg(test)]
#[allow(clippy::expect_used)]
mod tests {
    use super::*;
    use simul::experiment::{CandidateId, FixedReplications, MasterSeed, run_serial};

    /// Evaluates `spec` across `reps` CRN replications and returns outcomes.
    fn eval_many(spec: SimSpec, reps: u32) -> Vec<PoolOutcome> {
        let schedule = FixedReplications::new(reps, 1);
        let records = run_serial(
            MasterSeed::from_u64(42),
            schedule.trials(CandidateId::new(0), spec),
            evaluate_run,
        )
        .expect("serial run");
        records
            .into_iter()
            .map(|r| r.result.expect("trial ok"))
            .collect()
    }

    #[test]
    fn hikari_sized_pool_beats_oversized_pool_under_usl_contention() {
        let mut tuned = SimSpec::default();
        tuned.pool.pooling = PoolingMode::Transaction;
        tuned.pool.pool_size = 14;
        tuned.workload.rps = 480.0;
        tuned.workload.horizon_ms = 7_000;
        tuned.workload.warmup_ms = 1_500;
        tuned.workload.burst_start_ms = 2_500;
        tuned.workload.burst_end_ms = 4_500;

        let mut oversized = tuned;
        oversized.pool.pool_size = 64;

        let tuned_out = eval_many(tuned, 4);
        let over_out = eval_many(oversized, 4);
        let tuned_p99: f64 = tuned_out.iter().map(|o| o.p99_ms).sum::<f64>() / 4.0;
        let over_p99: f64 = over_out.iter().map(|o| o.p99_ms).sum::<f64>() / 4.0;
        let tuned_tput: f64 = tuned_out.iter().map(|o| o.throughput_rps).sum::<f64>() / 4.0;
        let over_tput: f64 = over_out.iter().map(|o| o.throughput_rps).sum::<f64>() / 4.0;

        assert!(
            tuned_p99 < over_p99,
            "tuned pool P99 ({tuned_p99:.1}ms) should beat oversized ({over_p99:.1}ms)"
        );
        assert!(
            tuned_tput > over_tput,
            "tuned pool throughput ({tuned_tput:.1}) should beat oversized ({over_tput:.1})"
        );
    }

    #[test]
    fn transaction_pooling_beats_session_hold_across_rpc() {
        let mut session = SimSpec::default();
        session.pool.pool_size = 14;
        session.pool.pooling = PoolingMode::Session;
        session.workload.horizon_ms = 6_000;
        session.workload.warmup_ms = 1_000;
        session.workload.burst_start_ms = 2_500;
        session.workload.burst_end_ms = 4_000;

        let mut txn = session;
        txn.pool.pooling = PoolingMode::Transaction;

        let s_out = eval_many(session, 4);
        let t_out = eval_many(txn, 4);
        let s_succ: f64 = s_out.iter().map(|o| o.success_rate).sum::<f64>() / 4.0;
        let t_succ: f64 = t_out.iter().map(|o| o.success_rate).sum::<f64>() / 4.0;
        assert!(
            t_succ > s_succ,
            "transaction pooling success ({t_succ:.3}) should exceed session ({s_succ:.3})"
        );
    }

    #[test]
    fn bulkhead_protects_fast_oltp_p99_from_slow_queries() {
        let mut shared = SimSpec::default();
        shared.pool.pool_size = 14;
        shared.pool.pooling = PoolingMode::Transaction;
        shared.pool.bulkhead = BulkheadMode::Shared;
        shared.workload.slow_frac = 0.06;
        shared.workload.horizon_ms = 6_000;
        shared.workload.warmup_ms = 1_000;
        shared.workload.burst_start_ms = 2_500;
        shared.workload.burst_end_ms = 4_000;

        let mut split = shared;
        split.pool.bulkhead = BulkheadMode::Split { slow_cap: 2 };

        let sh_out = eval_many(shared, 4);
        let sp_out = eval_many(split, 4);
        let sh_fast: f64 = sh_out.iter().map(|o| o.fast_p99_ms).sum::<f64>() / 4.0;
        let sp_fast: f64 = sp_out.iter().map(|o| o.fast_p99_ms).sum::<f64>() / 4.0;
        assert!(
            sp_fast < sh_fast,
            "split bulkhead fast P99 ({sp_fast:.1}ms) should beat shared ({sh_fast:.1}ms)"
        );
    }

    #[test]
    fn nested_acquisition_triggers_exact_deadlock_and_non_nested_never_does() {
        let mut nested = SimSpec::default();
        nested.pool.pool_size = 6;
        nested.pool.acquire_timeout_ms = 5_000;
        nested.pool.halt_on_deadlock = true;
        nested.pool.pooling = PoolingMode::Transaction;
        nested.workload.nested_frac = 0.30;
        nested.workload.rpc_hold_frac = 0.0;
        nested.workload.slow_frac = 0.02;
        nested.workload.horizon_ms = 6_000;

        let mut safe = nested;
        safe.workload.nested_frac = 0.0;

        let n_out = eval_many(nested, 8);
        let s_out = eval_many(safe, 8);
        assert!(
            n_out
                .iter()
                .any(|o| o.deadlocked && o.deadlock_tick.is_some()),
            "small pool with 30% nested acquisitions must hit exact deadlock"
        );
        assert!(
            s_out.iter().all(|o| !o.deadlocked),
            "non-nested workload must never deadlock"
        );
    }
}
